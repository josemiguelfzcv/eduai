-- The three tables production had before Lyceo's own migrations (users, courses, session_events), reconstructed from
-- what the code reads and writes.
--
-- STAGING AND LOCAL TESTS ONLY. Production already has these tables; never run this there.
-- It's a best guess until supabase/checks/rls_audit.sql has been run on production: then replace it with production's
-- real columns, defaults, foreign keys, grants and policies, so staging behaves like production.

create table if not exists public.users (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  name text,
  career text,
  learning_style text,
  created_at timestamptz not null default now()
);

-- One generated lesson. (The name predates My Academy, where "course" means a class the student takes.)
create table if not exists public.courses (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  title text,
  description text,
  status text,
  script jsonb,
  created_at timestamptz not null default now()
);

-- One answer to a lesson check-in.
create table if not exists public.session_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  course_id bigint not null references public.courses (id) on delete cascade,
  segment_index integer not null,
  question text,
  answer text,
  correct boolean,
  time_to_answer_seconds integer,
  created_at timestamptz not null default now()
);

alter table public.users enable row level security;
alter table public.courses enable row level security;
alter table public.session_events enable row level security;

grant select, insert, update, delete on public.users to authenticated;
grant select, insert, update, delete on public.courses to authenticated;
grant select, insert, update, delete on public.session_events to authenticated;

drop policy if exists "users_own" on public.users;
create policy "users_own" on public.users for all to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

drop policy if exists "courses_own" on public.courses;
create policy "courses_own" on public.courses for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

drop policy if exists "session_events_own" on public.session_events;
create policy "session_events_own" on public.session_events for all to authenticated
  using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
